import {chromium} from 'playwright';
import fs from 'node:fs/promises';
const browser=await chromium.launch({channel:'chrome',headless:true,args:['--enable-webgl','--ignore-gpu-blocklist']});
const page=await browser.newPage({viewport:{width:1600,height:900},deviceScaleFactor:1});
const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
await page.goto('http://127.0.0.1:5173/');
await page.waitForFunction(()=>window.oc8,{timeout:120000});
await page.evaluate(()=>oc8.inspect(.25,0));
await page.screenshot({path:'artifacts/hero-initial.png'});
console.log(JSON.stringify({snapshot:await page.evaluate(()=>oc8.snapshot()),errors},null,2));
await browser.close();
